-- Second dataset: the "Farah Family 799" GEDCOM, kept in its own table so the original
-- `persons` table (480 people) is untouched. Run in the SQL Editor, then run seed-799.sql.
-- Requires schema.sql to have been run first (it defines public.persons_touch()).
-- Names in this dataset are English; name_ar optionally overrides the automatic Arabic rendering.

create table if not exists public.persons_799 (
  id          bigint generated by default as identity primary key,
  gedcom_id   text unique,
  name        text not null check (length(trim(name)) > 0),
  name_ar     text,
  sex         char(1) not null default 'U' check (sex in ('M', 'F', 'U')),
  father_id   bigint references public.persons_799 (id) on delete restrict,
  mother_name text,
  birth_date  text,
  death_date  text,
  birth_place text,
  notes       text,
  photo_url   text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  created_by  uuid default auth.uid() references auth.users (id) on delete set null,
  updated_by  uuid references auth.users (id) on delete set null
);

create index if not exists persons_799_father_id_idx on public.persons_799 (father_id);

drop trigger if exists persons_799_touch on public.persons_799;
create trigger persons_799_touch before update on public.persons_799
for each row execute function public.persons_touch();

alter table public.persons_799 enable row level security;

drop policy if exists "persons_799 are public" on public.persons_799;
create policy "persons_799 are public" on public.persons_799
  for select using (true);

drop policy if exists "signed-in users can add 799" on public.persons_799;
create policy "signed-in users can add 799" on public.persons_799
  for insert to authenticated with check (true);

drop policy if exists "signed-in users can edit 799" on public.persons_799;
create policy "signed-in users can edit 799" on public.persons_799
  for update to authenticated using (true) with check (true);

drop policy if exists "signed-in users can delete 799" on public.persons_799;
create policy "signed-in users can delete 799" on public.persons_799
  for delete to authenticated using (true);
