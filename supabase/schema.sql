-- Farah Family Tree - Supabase schema
-- Run this in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- Then run seed.sql to load the people from the GEDCOM file.

create table if not exists public.persons (
  id          bigint generated by default as identity primary key,
  gedcom_id   text unique,
  name        text not null check (length(trim(name)) > 0),
  sex         char(1) not null default 'U' check (sex in ('M', 'F', 'U')),
  father_id   bigint references public.persons (id) on delete restrict,
  mother_name text,
  birth_date  text,
  death_date  text,
  birth_place text,
  notes       text,
  photo_url   text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  created_by  uuid default auth.uid() references auth.users (id) on delete set null,
  updated_by  uuid references auth.users (id) on delete set null
);

create index if not exists persons_father_id_idx on public.persons (father_id);

-- Keep updated_at / updated_by current on every edit.
create or replace function public.persons_touch()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  new.updated_by := auth.uid();
  return new;
end $$;

drop trigger if exists persons_touch on public.persons;
create trigger persons_touch before update on public.persons
for each row execute function public.persons_touch();

-- Row Level Security: everyone can read, only signed-in users can change.
-- IMPORTANT: in Authentication -> Sign In / Providers, turn OFF "Allow new users to sign up"
-- and invite family editors from Authentication -> Users, so only they can log in.
alter table public.persons enable row level security;

drop policy if exists "persons are public" on public.persons;
create policy "persons are public" on public.persons
  for select using (true);

drop policy if exists "signed-in users can add" on public.persons;
create policy "signed-in users can add" on public.persons
  for insert to authenticated with check (true);

drop policy if exists "signed-in users can edit" on public.persons;
create policy "signed-in users can edit" on public.persons
  for update to authenticated using (true) with check (true);

drop policy if exists "signed-in users can delete" on public.persons;
create policy "signed-in users can delete" on public.persons
  for delete to authenticated using (true);
