"""Convert the Farah family GEDCOM file into site data.

Outputs:
  data/family.json     - offline/demo data used when Supabase is not configured
  supabase/seed.sql    - INSERT statements for the `persons` table

Usage:
  python tools/gedcom_to_data.py "Farah Family 480.ged"
  python tools/gedcom_to_data.py Farah-Family-799.ged 799 --strip-surname Farah

Without a dataset key the original files are written (data/family.json, supabase/seed.sql,
table `persons`). With a key such as 799 the output is kept separate: data/family-799.json,
supabase/seed-799.sql and table `persons_799`.
--strip-surname drops a trailing family name ("Elias Farah" -> "Elias") so names read like the
Arabic dataset; it is only needed for files that repeat the surname on every person.
"""
import argparse
import json
import re
import sys
from collections import defaultdict, deque
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def parse_gedcom(path):
    indis, fams = {}, {}
    cur = None
    data = Path(path).read_bytes()
    try:
        text = data.decode("utf-8-sig")
    except UnicodeDecodeError:  # GEDCOM exports declared "CHAR ANSI"
        text = data.decode("cp1252")
    for raw in text.splitlines():
        parts = raw.strip().split(" ", 2)
        if len(parts) < 2:
            continue
        level = parts[0]
        if level == "0":
            cur = None
            if len(parts) == 3 and parts[2] == "INDI":
                cur = indis.setdefault(parts[1], {"id": parts[1], "name": "", "sex": "U"})
            elif len(parts) == 3 and parts[2] == "FAM":
                cur = fams.setdefault(parts[1], {"husb": None, "wife": None, "chil": []})
            continue
        if cur is None or level != "1":
            continue
        tag, val = parts[1], parts[2] if len(parts) == 3 else ""
        if tag == "NAME":
            cur["name"] = re.sub(r"\s+", " ", val.replace("/", " ")).strip()
        elif tag == "SEX":
            cur["sex"] = val if val in ("M", "F") else "U"
        elif tag == "HUSB":
            cur["husb"] = val
        elif tag == "WIFE":
            cur["wife"] = val
        elif tag == "CHIL":
            cur["chil"].append(val)
    return indis, fams


def num(gid):
    return int(re.sub(r"\D", "", gid))


def strip_surname(name, surname):
    words = name.split()
    for i in range(len(words) - 1, 0, -1):
        if words[i] == surname:
            del words[i]
            break
    return " ".join(words)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ged", nargs="?", default=str(ROOT / "Farah Family 480.ged"))
    ap.add_argument("key", nargs="?", default=None, help="dataset key, e.g. 799")
    ap.add_argument("--strip-surname", default=None)
    args = ap.parse_args()
    suffix = f"-{args.key}" if args.key else ""
    table = f"persons_{args.key}" if args.key else "persons"
    indis, fams = parse_gedcom(args.ged)
    if args.strip_surname:
        for i in indis.values():
            i["name"] = strip_surname(i["name"], args.strip_surname)

    father = {}
    for fam in fams.values():
        if fam["husb"]:
            for c in fam["chil"]:
                father[c] = fam["husb"]

    children = defaultdict(list)
    for c, f in father.items():
        children[f].append(c)

    # Parents before children so foreign keys resolve in order.
    roots = sorted((i for i in indis if i not in father), key=num)
    order, queue = [], deque(roots)
    while queue:
        gid = queue.popleft()
        order.append(gid)
        queue.extend(children[gid])

    persons = [
        {
            "id": num(g),
            "gedcom_id": g.strip("@"),
            "name": indis[g]["name"],
            "sex": indis[g]["sex"],
            "father_id": num(father[g]) if g in father else None,
        }
        for g in order
    ]

    (ROOT / "data").mkdir(exist_ok=True)
    (ROOT / "data" / f"family{suffix}.json").write_text(
        "[\n" + ",\n".join(json.dumps(p, ensure_ascii=False) for p in persons) + "\n]\n",
        encoding="utf-8",
    )

    def q(v):
        return "null" if v is None else "'" + str(v).replace("'", "''") + "'"

    rows = ",\n".join(
        f"  ({p['id']}, {q(p['gedcom_id'])}, {q(p['name'])}, {q(p['sex'])}, {p['father_id'] or 'null'})"
        for p in persons
    )
    sql = (
        f"-- Generated by tools/gedcom_to_data.py - run after the schema for public.{table}\n"
        f"insert into public.{table} (id, gedcom_id, name, sex, father_id) values\n"
        f"{rows}\n"
        "on conflict (id) do nothing;\n\n"
        f"select setval(pg_get_serial_sequence('public.{table}', 'id'),"
        f" (select max(id) from public.{table}));\n"
    )
    (ROOT / "supabase").mkdir(exist_ok=True)
    (ROOT / "supabase" / f"seed{suffix}.sql").write_text(sql, encoding="utf-8")

    print(f"{len(persons)} persons, {len(roots)} root(s): {[indis[r]['name'] for r in roots]}".encode("ascii", "replace").decode())
    depth = {}
    for g in order:
        depth[g] = depth[father[g]] + 1 if g in father else 1
    print("generations:", max(depth.values()))


if __name__ == "__main__":
    main()
