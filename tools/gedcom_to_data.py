"""Convert the Farah family GEDCOM file into site data.

Outputs:
  data/family.json     - offline/demo data used when Supabase is not configured
  supabase/seed.sql    - INSERT statements for the `persons` table

Usage:
  python tools/gedcom_to_data.py "Farah Family 480.ged"
"""
import json
import re
import sys
from collections import defaultdict, deque
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def parse_gedcom(path):
    indis, fams = {}, {}
    cur = None
    for raw in Path(path).read_text(encoding="utf-8-sig").splitlines():
        parts = raw.strip().split(" ", 2)
        if len(parts) < 2:
            continue
        level = parts[0]
        if level == "0":
            cur = None
            if len(parts) == 3 and parts[2] == "INDI":
                cur = indis.setdefault(parts[1], {"id": parts[1], "name": "", "sex": "U"})
            elif len(parts) == 3 and parts[2] == "FAM":
                cur = fams.setdefault(parts[1], {"husb": None, "wife": None, "chil": []})
            continue
        if cur is None or level != "1":
            continue
        tag, val = parts[1], parts[2] if len(parts) == 3 else ""
        if tag == "NAME":
            cur["name"] = re.sub(r"\s+", " ", val.replace("/", " ")).strip()
        elif tag == "SEX":
            cur["sex"] = val if val in ("M", "F") else "U"
        elif tag == "HUSB":
            cur["husb"] = val
        elif tag == "WIFE":
            cur["wife"] = val
        elif tag == "CHIL":
            cur["chil"].append(val)
    return indis, fams


def num(gid):
    return int(re.sub(r"\D", "", gid))


def main():
    ged = sys.argv[1] if len(sys.argv) > 1 else ROOT / "Farah Family 480.ged"
    indis, fams = parse_gedcom(ged)

    father = {}
    for fam in fams.values():
        if fam["husb"]:
            for c in fam["chil"]:
                father[c] = fam["husb"]

    children = defaultdict(list)
    for c, f in father.items():
        children[f].append(c)

    # Parents before children so foreign keys resolve in order.
    roots = sorted((i for i in indis if i not in father), key=num)
    order, queue = [], deque(roots)
    while queue:
        gid = queue.popleft()
        order.append(gid)
        queue.extend(children[gid])

    persons = [
        {
            "id": num(g),
            "gedcom_id": g.strip("@"),
            "name": indis[g]["name"],
            "sex": indis[g]["sex"],
            "father_id": num(father[g]) if g in father else None,
        }
        for g in order
    ]

    (ROOT / "data").mkdir(exist_ok=True)
    (ROOT / "data" / "family.json").write_text(
        "[\n" + ",\n".join(json.dumps(p, ensure_ascii=False) for p in persons) + "\n]\n",
        encoding="utf-8",
    )

    def q(v):
        return "null" if v is None else "'" + str(v).replace("'", "''") + "'"

    rows = ",\n".join(
        f"  ({p['id']}, {q(p['gedcom_id'])}, {q(p['name'])}, {q(p['sex'])}, {p['father_id'] or 'null'})"
        for p in persons
    )
    sql = (
        "-- Generated by tools/gedcom_to_data.py - run after schema.sql\n"
        "insert into public.persons (id, gedcom_id, name, sex, father_id) values\n"
        f"{rows}\n"
        "on conflict (id) do nothing;\n\n"
        "select setval(pg_get_serial_sequence('public.persons', 'id'),"
        " (select max(id) from public.persons));\n"
    )
    (ROOT / "supabase").mkdir(exist_ok=True)
    (ROOT / "supabase" / "seed.sql").write_text(sql, encoding="utf-8")

    print(f"{len(persons)} persons, {len(roots)} root(s): {[indis[r]['name'] for r in roots]}")
    depth = {}
    for g in order:
        depth[g] = depth[father[g]] + 1 if g in father else 1
    print("generations:", max(depth.values()))


if __name__ == "__main__":
    main()
